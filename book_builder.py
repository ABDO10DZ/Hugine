# ─── verify ──────────────────────────────────────────────────────────────────
def verify_book(path: str):
    """Check that the book is sorted by key (required by binary search in engines)."""
    with open(path, 'rb') as f:
        data = f.read()
    n = len(data) // 16
    prev = 0
    errors = 0
    for i in range(0, len(data), 16):
        key, _, _, _ = struct.unpack('>QHHI', data[i:i+16])
        if key < prev: errors += 1
        prev = key
    if errors:
        print(f"[FAIL] {path}: {errors} ordering violations — book may not work correctly")
    else:
        print(f"[OK]   {path}: {n} entries, correctly sorted")


# ─── CLI ─────────────────────────────────────────────────────────────────────
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd')

    # build
    p_build = sub.add_parser('build', help='Build book from PGN file(s)')
    p_build.add_argument('--pgn',       nargs='+', required=True, help='PGN file(s) or glob patterns')
    p_build.add_argument('--out',       default='book.bin',   help='Output .bin file')
    p_build.add_argument('--depth',     type=int, default=30,  help='Max half-moves per game')
    p_build.add_argument('--min-freq',  type=int, default=2,   help='Min occurrence count')
    p_build.add_argument('--result',    choices=['all','w','b','d'], default='all')
    p_build.add_argument('--weight',    choices=['freq','score','uniform'], default='freq')
    p_build.add_argument('--polyglot',  action='store_true',   help='Use standard Polyglot hash')
    p_build.add_argument('--verbose',   action='store_true')

    # merge
    p_merge = sub.add_parser('merge', help='Merge two or more .bin books')
    p_merge.add_argument('books', nargs='+')
    p_merge.add_argument('--out', required=True)

    # dump
    p_dump = sub.add_parser('dump', help='Print book entries')
    p_dump.add_argument('book')
    p_dump.add_argument('--max', type=int, default=50)

    # stats
    p_stats = sub.add_parser('stats', help='Book statistics')
    p_stats.add_argument('book')

    # verify
    p_verify = sub.add_parser('verify', help='Verify book ordering')
    p_verify.add_argument('book')

    args = ap.parse_args()
    if not args.cmd:
        ap.print_help(); return

    if args.cmd == 'build':
        pgn_files = []
        for pattern in args.pgn:
            expanded = glob.glob(pattern)
            pgn_files.extend(expanded if expanded else [pattern])
        n, g = build_book(
            pgn_files=pgn_files, out_path=args.out,
            depth=args.depth, min_freq=args.min_freq,
            result_filter=args.result, weight_scheme=args.weight,
            use_polyglot=args.polyglot, verbose=args.verbose)
        print(f"Done: {n} entries from {g} games → {args.out}")

    elif args.cmd == 'merge':
        merge_books(args.books, args.out)
    elif args.cmd == 'dump':
        dump_book(args.book, args.max)
    elif args.cmd == 'stats':
        book_stats(args.book)
    elif args.cmd == 'verify':
        verify_book(args.book)

if __name__ == '__main__':
    main()
